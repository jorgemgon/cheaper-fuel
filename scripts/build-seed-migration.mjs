#!/usr/bin/env node
/**
 * Compile data/discounts.seed.json into a D1 migration.
 *
 * Migrations are append-only: every run writes the next numbered file, so an
 * already-applied migration is never rewritten.
 *
 *   npm run discounts:migration -- --name add-repsol-values
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const seedPath = path.join(root, "data", "discounts.seed.json");
const migrationsDir = path.join(root, "migrations");

const COLUMNS = [
  "id",
  "schema_version",
  "program_id",
  "program_title",
  "description",
  "tier_id",
  "tier_label",
  "tier_rank",
  "kind",
  "supplier",
  "partners_json",
  "brands_json",
  "name_prefixes_json",
  "requires_json",
  "min_services",
  "channel",
  "value_type",
  "value",
  "combine",
  "cap_litres_per_fill",
  "cap_litres_per_year",
  "schedule_kind",
  "schedule_weekdays_json",
  "schedule_days_of_month_json",
  "schedule_nth",
  "schedule_weekday",
  "valid_from",
  "valid_until",
  "confidence",
  "source_url",
  "source_retrieved_at",
  "source_hash",
  "source_fetch_mode",
  "notes",
  "updated_at",
];

function sqlText(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlNumber(value) {
  if (value === null || value === undefined) return "NULL";
  const parsed = Number(value);
  return Number.isFinite(parsed) ? String(parsed) : "NULL";
}

function sqlArray(values) {
  if (!Array.isArray(values) || values.length === 0) return "'[]'";
  return sqlText(JSON.stringify(values));
}

function toRow(entry) {
  return [
    sqlText(entry.id),
    sqlNumber(entry.schemaVersion ?? 1),
    sqlText(entry.programId),
    sqlText(entry.programTitle),
    sqlText(entry.description),
    sqlText(entry.tierId),
    sqlText(entry.tierLabel),
    sqlNumber(entry.tierRank ?? 0),
    sqlText(entry.kind),
    sqlText(entry.supplier),
    sqlArray(entry.partners),
    sqlArray(entry.stationMatch?.brands),
    sqlArray(entry.stationMatch?.namePrefixes),
    sqlArray(entry.requires),
    sqlNumber(entry.minServices ?? 0),
    sqlText(entry.channel),
    sqlText(entry.valueType),
    sqlNumber(entry.value),
    sqlText(entry.combine ?? "sum"),
    sqlNumber(entry.caps?.litresPerFill),
    sqlNumber(entry.caps?.litresPerYear),
    sqlText(entry.schedule?.kind ?? "always"),
    sqlArray(entry.schedule?.weekdays),
    sqlArray(entry.schedule?.daysOfMonth),
    sqlNumber(entry.schedule?.nth),
    sqlNumber(entry.schedule?.weekday),
    sqlText(entry.validFrom),
    sqlText(entry.validUntil),
    sqlText(entry.confidence),
    sqlText(entry.source?.url),
    sqlText(entry.source?.retrievedAt),
    sqlText(entry.source?.contentHash),
    sqlText(entry.source?.fetchMode ?? "auto"),
    sqlText(entry.source?.notes),
    sqlText(entry.updatedAt),
  ];
}

function argValue(flag) {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

const seed = JSON.parse(await readFile(seedPath, "utf8"));
const entries = seed.discounts ?? [];

const ids = new Set();
for (const entry of entries) {
  for (const field of ["id", "programId", "programTitle", "description", "kind", "supplier", "channel", "confidence"]) {
    if (!entry[field]) throw new Error(`seed entry ${entry.id ?? "<no id>"} is missing ${field}`);
  }
  if (ids.has(entry.id)) throw new Error(`duplicate discount id: ${entry.id}`);
  ids.add(entry.id);
  const hasValue = entry.valueType !== null && entry.value !== null;
  const hasPartial = (entry.valueType === null) !== (entry.value === null);
  if (hasPartial) throw new Error(`${entry.id}: valueType and value must both be set or both be null`);
  if (entry.valueType !== null && !hasValue) throw new Error(`${entry.id}: invalid value`);
  if (entry.validFrom && entry.validUntil && entry.validFrom > entry.validUntil) {
    throw new Error(`${entry.id}: validFrom must be on or before validUntil`);
  }
}

const existing = (await readdir(migrationsDir)).filter((name) => /^\d{4}_.*\.sql$/.test(name));
const nextNumber = Math.max(1, ...existing.map((name) => Number(name.slice(0, 4)))) + 1;
const suffix = (argValue("--name") ?? "seed_discounts").replace(/[^a-z0-9_]/gi, "_");
const fileName = `${String(nextNumber).padStart(4, "0")}_${suffix}.sql`;

const updates = COLUMNS.filter((column) => column !== "id")
  .map((column) => `  ${column} = excluded.${column}`)
  .join(",\n");

const statements = entries.map((entry) => {
  const values = toRow(entry).join(", ");
  return (
    `INSERT INTO discounts (${COLUMNS.join(", ")})\n` +
    `VALUES (${values})\n` +
    `ON CONFLICT(id) DO UPDATE SET\n${updates};`
  );
});

const idList = [...ids].map((id) => sqlText(id)).join(", ");
statements.push(`DELETE FROM discounts WHERE id NOT IN (${idList});`);

const header = [
  `-- Generated by scripts/build-seed-migration.mjs from data/discounts.seed.json.`,
  `-- Do not edit by hand: change the seed and regenerate.`,
  `-- Registry updated_at: ${seed.updatedAt ?? "unknown"}`,
  ``,
].join("\n");

const outputPath = path.join(migrationsDir, fileName);
await writeFile(outputPath, `${header}${statements.join("\n\n")}\n`, "utf8");

console.log(`Wrote ${path.relative(root, outputPath)} with ${entries.length} discount(s).`);
